namespace Taskly.Contracts.Enums.Issues;

/// <summary>
/// Defines the priority levels for issues and task items.
/// </summary>
public enum IssuePriority
{
    /// <summary>
    /// High priority - requires immediate attention.
    /// </summary>
    High = 1,

    /// <summary>
    /// Medium priority - normal importance.
    /// </summary>
    Medium = 2,

    /// <summary>
    /// Low priority - can be addressed when time permits.
    /// </summary>
    Low = 3,
}
